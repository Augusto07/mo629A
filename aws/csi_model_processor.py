import numpy as np


def _median(values):
    values = np.asarray(values)
    good = values[np.isfinite(values)]
    return float(np.median(good)) if good.size else float('nan')


def _shape_features(x):
    centered = x - np.mean(x, axis=0)
    std = np.std(x, axis=0)
    active = std > 1e-10
    if not np.any(active):
        return 0.0, 0.0
    z = centered[:, active] / std[active]
    singular = np.linalg.svd(z, compute_uv=False)
    pca_fraction = float(singular[0] ** 2 / np.sum(singular ** 2))
    if z.shape[1] < 2:
        return float('nan'), pca_fraction
    correlation = (z.T @ z) / len(z)
    pairs = np.triu_indices(z.shape[1], 1)
    return float(np.mean(np.abs(correlation[pairs]))), pca_fraction


def _periodicity(t, x, band, min_cycles):
    """Sinusoid fits at actual timestamps, after removing a linear trend.

    Scores are fractions of detrended variance explained, not a calibrated PSD.
    Aggregate across informative bins by the median, rather than picking one bin.
    """
    span = t[-1] - t[0]
    lower = max(band[0], min_cycles / span)
    if lower >= band[1]:
        return float('nan'), float('nan')
    t = t - t[0]
    trend = np.column_stack([np.ones(len(t)), t])
    residual = x - trend @ np.linalg.lstsq(trend, x, rcond=None)[0]
    energy = np.sum(residual ** 2, axis=0)
    usable = energy > 1e-10
    if not np.any(usable):
        return float('nan'), 0.0
    residual = residual[:, usable]
    energy = energy[usable]
    frequencies = np.linspace(lower, band[1], 160)
    scores = []
    for frequency in frequencies:
        basis = np.column_stack([np.sin(2 * np.pi * frequency * t),
                                 np.cos(2 * np.pi * frequency * t)])
        # Residualize the sinusoid too, to compare against a trend-only model.
        basis -= trend @ np.linalg.lstsq(trend, basis, rcond=None)[0]
        fitted = basis @ np.linalg.lstsq(basis, residual, rcond=None)[0]
        scores.append(np.median(np.clip(np.sum(fitted ** 2, axis=0) / energy, 0, 1)))
    best = int(np.argmax(scores))
    return float(frequencies[best]), float(scores[best])


def extract_features(time_s, channel, bins=None, window_seconds=30.0,
                     hop_seconds=5.0, min_packets=12, max_gap_seconds=2.0,
                     periodic_band=(0.1, 0.5), min_cycles=3,
                     start_s=None, end_s=None):
    """Return one dict per complete window. Inadequate windows remain flagged.

    Pair indices retain original buffer positions. Invalid samples must already
    be NaN. Phase is uncalibrated; phase features are exploratory diagnostics.
    Explicit start/end bounds support rolling buffers without shifting the
    window grid to the first packet that happens to survive an upload gap.
    """
    t = np.asarray(time_s, dtype=float)
    h = np.asarray(channel, dtype=complex)
    if t.ndim != 1 or h.ndim != 2 or h.shape[0] != len(t):
        raise ValueError('Expected time (packets,) and channel (packets, bins).')
    if ((len(t) < 2 and (start_s is None or end_s is None)) or
            not np.all(np.isfinite(t)) or np.any(np.diff(t) < 0)):
        raise ValueError('At least two finite, nondecreasing timestamps required.')
    if window_seconds <= 0 or hop_seconds <= 0 or max_gap_seconds <= 0:
        raise ValueError('Window, hop, and maximum gap must be positive.')
    if not 0 < periodic_band[0] < periodic_band[1] or min_packets < 3 or min_cycles < 1:
        raise ValueError('Invalid periodic band, packet count, or cycle count.')
    if bins is not None:
        h = h[:, bins]
    names = ['amplitude_mean', 'amplitude_std_median', 'amplitude_mad_median',
             'amplitude_cv_median', 'amplitude_step_median',
             'amplitude_change_rate_median', 'normalized_std_median',
             'normalized_step_median', 'subcarrier_abs_correlation',
             'pca1_variance_fraction', 'phase_step_abs_median_rad',
             'relative_phase_step_abs_median_rad', 'periodic_peak_hz',
             'periodic_explained_fraction']
    rows = []
    start = float(t[0]) if start_s is None else float(start_s)
    end = float(t[-1]) if end_s is None else float(end_s)
    if not np.isfinite(start) or not np.isfinite(end) or end < start:
        raise ValueError('Window bounds must be finite and nondecreasing.')
    while start + window_seconds <= end + 1e-9:
        stop = start + window_seconds
        mask = (t >= start) & (t < stop)
        tw, hw = t[mask], h[mask]
        row = dict(window_start_s=start, window_end_s=stop,
                   window_center_s=(start + stop) / 2, packet_count=len(tw),
                   bin_count=0, imputed_fraction=float('nan'),
                   packet_rate_hz=0.0, max_gap_s=window_seconds,
                   quality_ok=False, periodicity_ok=False)
        row.update({name: float('nan') for name in names})
        rows.append(row)
        start += hop_seconds
        if len(tw) < min_packets:
            continue
        gaps = np.diff(tw)
        positive = gaps > 0
        row['packet_rate_hz'] = float((len(tw) - 1) / (tw[-1] - tw[0])) if tw[-1] > tw[0] else 0.0
        # Include unobserved edges of the requested window in the gap metric.
        row['max_gap_s'] = float(max(np.max(gaps), tw[0] - (stop-window_seconds), stop-tw[-1]))
        amplitude = np.abs(hw)
        good = (np.mean(np.isfinite(amplitude), axis=0) >= 0.8)
        good &= np.any(np.isfinite(amplitude) & (amplitude > 0), axis=0)
        if not np.any(good):
            continue
        hw, amplitude = hw[:, good], amplitude[:, good]
        row['bin_count'] = amplitude.shape[1]
        row['imputed_fraction'] = float(np.mean(~np.isfinite(amplitude)))
        medians = np.nanmedian(amplitude, axis=0)
        spread = np.nanstd(amplitude, axis=0)
        row['amplitude_mean'] = float(np.nanmean(amplitude))
        row['amplitude_std_median'] = _median(spread)
        row['amplitude_mad_median'] = _median(np.nanmedian(np.abs(amplitude-medians), axis=0))
        means = np.nanmean(amplitude, axis=0)
        row['amplitude_cv_median'] = _median(np.divide(spread, means, out=np.full_like(means, np.nan), where=means > 1e-10))
        # Normalize per packet across bins; keep raw features as well.
        scale = np.nanmean(amplitude, axis=1, keepdims=True)
        normalized = np.divide(amplitude, scale, out=np.full_like(amplitude, np.nan), where=scale > 1e-10)
        row['normalized_std_median'] = _median(np.nanstd(normalized, axis=0))
        adjacent = positive & (gaps <= max_gap_seconds)
        if np.any(adjacent):
            steps = np.abs(np.diff(amplitude, axis=0))[adjacent]
            row['amplitude_step_median'] = _median(steps)
            row['amplitude_change_rate_median'] = _median(steps / gaps[adjacent, None])
            row['normalized_step_median'] = _median(np.abs(np.diff(normalized, axis=0))[adjacent])
            # Circular increments avoid interpreting a +/-pi crossing as a jump.
            ph = np.angle(hw)
            ph[(amplitude == 0) | ~np.isfinite(amplitude)] = np.nan
            delta = np.angle(np.exp(1j * np.diff(ph, axis=0)))[adjacent]
            row['phase_step_abs_median_rad'] = _median(np.abs(delta))
            # Remove the circular common phase increment per packet pair.
            # This is not full phase calibration or a two-antenna CSI ratio.
            count = np.sum(np.isfinite(delta), axis=1)
            common = np.angle(np.nansum(np.exp(1j * delta), axis=1))
            relative = np.angle(np.exp(1j * (delta - common[:, None])))
            relative[count < 2] = np.nan
            row['relative_phase_step_abs_median_rad'] = _median(np.abs(relative))
        # Multivariate/spectral calculations use median imputation, reported above.
        fill = np.nanmedian(normalized, axis=0)
        usable = np.isfinite(fill)
        x = normalized[:, usable]
        if x.shape[1] == 0:
            continue
        x = np.where(np.isfinite(x), x, fill[usable])
        corr, pca = _shape_features(x)
        row['subcarrier_abs_correlation'] = corr
        row['pca1_variance_fraction'] = pca
        row['quality_ok'] = bool(row['max_gap_s'] <= max_gap_seconds)
        # A rate guard is necessary but does not eliminate irregular-sampling aliases.
        if row['quality_ok'] and row['packet_rate_hz'] > 2 * periodic_band[1]:
            frequency, score = _periodicity(tw, x, periodic_band, min_cycles)
            row['periodic_peak_hz'] = frequency
            row['periodic_explained_fraction'] = score
            row['periodicity_ok'] = bool(np.isfinite(frequency))
    return rows

def read_capture(path):
    """Decode this example's CSI; reject mixed source/channel/format captures."""
    records, malformed = [], 0
    if True:
        for row in read_records(path):
            if row.get('type', 'CSI_DATA') != 'CSI_DATA':
                continue
            try:
                values = json.loads(row['data']) if isinstance(row['data'], str) else row['data']
                if not isinstance(values, list) or not all(type(v) is int for v in values):
                    raise ValueError('Noninteger data')
                if len(values) < 2 or len(values) % 2 or len(values) != int(row['len']):
                    raise ValueError('Bad length')
                collector_clock = 'timestamp_us' in row
                stamp = int(row['timestamp_us'] if collector_clock else row['local_timestamp'])
                invalid = int(row['first_word'])
                # Firmware prints the uint32 microsecond counter with %d, so
                # valid counters above INT32_MAX may appear as signed negatives.
                valid_stamp = (0 <= stamp < 2**63 if collector_clock
                               else -(2**31) <= stamp < 2**32)
                if not valid_stamp or invalid not in (0, 1):
                    raise ValueError('Bad metadata')
                if not collector_clock:
                    stamp = stamp % (2**32)
                group = (str(row.get('mac')), str(row.get('channel')), str(row.get('sig_mode', row.get('rx_format'))),
                         str(row.get('bandwidth')), len(values))
                records.append((stamp, invalid, values, group, collector_clock))
            except (ValueError, KeyError, TypeError):
                malformed += 1
    if len(records) < 2:
        raise ValueError(f'{path}: fewer than two valid packets')
    if len({r[3] for r in records}) != 1:
        raise ValueError(f'{path}: multiple links/channels/formats; split into separate captures')
    if len({r[4] for r in records}) != 1:
        raise ValueError('Mixed collector and driver timestamp clocks; split captures first')
    stamps = np.array([r[0] for r in records], dtype=np.int64)
    delta = np.diff(stamps)
    if not records[0][4]:
        delta = np.where(delta < -(2**31), delta + 2**32, delta)
    if np.any(delta < 0):
        raise ValueError(f'{path}: clock reset/out-of-order packets; split sessions first')
    time = np.r_[0, np.cumsum(delta)] / 1e6
    raw = np.asarray([r[2] for r in records], dtype=float)
    channel = raw[:, 1::2] + 1j * raw[:, 0::2]
    channel[np.array([bool(r[1]) for r in records]), :2] = complex(np.nan, np.nan)
    timestamps = [int(stamps[0])]
    for step in delta:
        timestamps.append(timestamps[-1] + int(step))
    metadata = dict(sample_timestamps_us=timestamps,
                    source_mac=records[0][3][0], channel=records[0][3][1],
                    format=str(records[0][3][2:]), malformed_packets=malformed)
    return time, channel, metadata


import numpy as np


def read_records(source):
    """Accept CSV, JSON/JSONL paths, a record dict, or a list of dicts.

    JSON may be a record, an array, or {"records": [...]} / {"data": [...]}.
    CSI's data field may be a native integer array or its CSV JSON string.
    """
    if isinstance(source, (str, Path)):
        text = Path(source).read_text(encoding='utf-8-sig').strip()
        if not text:
            return []
        if text[0] in '[{':
            try:
                source = json.loads(text)
            except json.JSONDecodeError:
                source = [json.loads(line) for line in text.splitlines() if line.strip()]
        else:
            import io
            source = list(csv.DictReader(io.StringIO(text)))
    if isinstance(source, dict):
        for key in ('records', 'rows', 'packets', 'data'):
            if isinstance(source.get(key), list) and all(isinstance(r, dict) for r in source[key]):
                source = source[key]
                break
        else:
            source = [source]
    if not isinstance(source, (list, tuple)) or not all(isinstance(r, dict) for r in source):
        raise ValueError('Expected a record object, array of record objects, or CSV/JSON/JSONL file')
    return [dict(row) for row in source]


def _matrix(values):
    if hasattr(values, "loc"):
        values = values.loc[:, FEATURES].to_numpy(dtype=float)
    x = np.asarray(values, dtype=float)
    if x.ndim == 1:
        x = x.reshape(1, -1)
    if x.ndim != 2 or x.shape[1] != len(FEATURES):
        raise ValueError(f"Expected rows with {len(FEATURES)} features in FEATURES order")
    return x


def impute(values):
    """Replace missing/nonfinite values with the fitted training medians."""
    x = _matrix(values).copy()
    return np.where(np.isfinite(x), x, np.asarray(COEFFICIENTS['imputer']['statistics_']))


def filter_variance(values):
    return np.asarray(values, dtype=float)[:, COEFFICIENTS['variance']['support']]


def scale(values):
    c = COEFFICIENTS['scaler']
    return (np.asarray(values, dtype=float) - np.asarray(c['mean_'])) / np.asarray(c['scale_'])


def transform(values):
    return scale(filter_variance(impute(values)))


def weighted_log_prob(values):
    """Evaluate the selected GMM's Gaussian densities in transformed space."""
    z = transform(values)
    c = COEFFICIENTS['model']
    means = np.asarray(c['means_'])
    precision_chol = np.asarray(c['precisions_cholesky_'])
    kind = c['covariance_type']
    differences = z[:, None, :] - means
    if kind == 'tied':
        transformed = z[:, None, :] @ precision_chol - means @ precision_chol
        log_det = np.log(np.diag(precision_chol)).sum()
    elif kind == 'full':
        transformed = np.einsum('nkd,kde->nke', differences, precision_chol)
        log_det = np.log(np.diagonal(precision_chol, axis1=1, axis2=2)).sum(axis=1)
    elif kind == 'diag':
        transformed = differences * precision_chol
        log_det = np.log(precision_chol).sum(axis=1)
    elif kind == 'spherical':
        transformed = differences * precision_chol[:, None]
        log_det = z.shape[1] * np.log(precision_chol)
    else:
        raise ValueError(f'Unsupported covariance type: {kind}')
    squared = np.sum(transformed ** 2, axis=2)
    return (-0.5 * (z.shape[1] * np.log(2 * np.pi) + squared)
            + log_det + np.log(np.asarray(c['weights_'])))


def score_samples(values):
    logs = weighted_log_prob(values)
    maximum = logs.max(axis=1)
    return maximum + np.log(np.exp(logs - maximum[:, None]).sum(axis=1))


def predict_proba(values):
    logs = weighted_log_prob(values)
    logs -= logs.max(axis=1, keepdims=True)
    probabilities = np.exp(logs)
    return probabilities / probabilities.sum(axis=1, keepdims=True)


def predict(values):
    return weighted_log_prob(values).argmax(axis=1)


# Runtime settings for short batches; original training provenance is preserved.
INFERENCE_PARAMETERS = dict(window_seconds=0.25, hop_seconds=0.25,
                            min_packets=3, max_gap_seconds=2.0)


def features_from_capture(path):
    """Extract short-window features without filtering by trained MAC/channel."""
    selected = {name: value for name, value in
                (PROVENANCE['metadata'].get('input_filter') or {}).items()
                if name not in ('mac', 'channel')}
    source = path
    if selected:
        source = [row for row in read_records(path)
                  if all(str(row.get(name, '')).strip() == str(value) for name, value in selected.items())]
        if len(source) < 2:
            raise ValueError('Capture has fewer than two packets matching the trained radio format')
    time, channel, metadata = read_capture(source)
    timestamps = metadata.pop('sample_timestamps_us')
    rows = extract_features(time, channel, **INFERENCE_PARAMETERS)
    for row in rows:
        row.update(metadata)
        row['window_parameters'] = dict(INFERENCE_PARAMETERS)
        row['settings_match_training'] = INFERENCE_PARAMETERS == PROVENANCE['metadata']['fast_parameters']
        row['inference_mode'] = 'exploratory_window_override'
        row['session_id'] = Path(path).stem if isinstance(path, (str, Path)) else 'capture'
        row['window_start_timestamp_us'] = timestamps[0] + round(row['window_start_s'] * 1e6)
        row['window_end_timestamp_us'] = timestamps[0] + round(row['window_end_s'] * 1e6)
        indices = np.flatnonzero((time >= row['window_start_s']) & (time < row['window_end_s']))
        row['sample_timestamps_us'] = [timestamps[index] for index in indices]
    return rows


def predict_capture(path):
    """Return all complete windows, retaining rejected windows as unknown."""
    rows = features_from_capture(path)
    return predict_records(rows)


def predict_records(rows):
    rows = [dict(row) for row in rows]
    for index, row in enumerate(rows):
        missing = set(FEATURES) - row.keys()
        if missing:
            raise ValueError(f'Feature record {index}: missing fields {sorted(missing)}')
    good = [row for row in rows if str(row.get('quality_ok', True)).strip().lower() in ('true', '1', 'yes')]
    for row in rows:
        row.update(state=None, log_likelihood=None, status='insufficient_data')
        if 'state_presence_mapping' in PROVENANCE['metadata']:
            row['presence_label'] = None
        for k in range(len(COEFFICIENTS['model']['weights_'])):
            row[f'membership_{k}'] = None
    if good:
        x = [[float(row[name]) if row[name] is not None and str(row[name]).strip() else np.nan
              for name in FEATURES] for row in good]
        labels, probabilities, scores = predict(x), predict_proba(x), score_samples(x)
        for row, label, probability, score in zip(good, labels, probabilities, scores):
            row.update(state=int(label), log_likelihood=float(score), status='ok')
            mapping = PROVENANCE['metadata'].get('state_presence_mapping')
            if mapping:
                row['presence_label'] = mapping[str(int(label))]
            row.update({f'membership_{k}': float(p) for k, p in enumerate(probability)})
    return rows


def predict_input(source, kind='auto'):
    """Predict from file or in-memory records; infer raw CSI vs feature fields."""
    rows = read_records(source)
    if not rows:
        return []
    if kind not in ('auto', 'raw', 'features'):
        raise ValueError('kind must be auto, raw, or features')
    if kind == 'auto':
        if all(set(FEATURES).issubset(row) for row in rows):
            kind = 'features'
        elif all({'data', 'local_timestamp', 'len', 'first_word'}.issubset(row)
                 for row in rows if row.get('type', 'CSI_DATA') == 'CSI_DATA') and any(
                     'local_timestamp' in row for row in rows):
            kind = 'raw'
        else:
            raise ValueError('Cannot infer input schema: expected CSI packet fields or all FEATURES')
    return predict_capture(rows) if kind == 'raw' else predict_records(rows)


