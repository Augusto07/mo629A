def _normalize_dynamodb_value(value):
    """Convert boto3 DynamoDB values to plain Python values accepted by NumPy."""
    from decimal import Decimal

    if isinstance(value, Decimal):
        # Preserve integer values as int; convert fractional values to float.
        return int(value) if value == value.to_integral_value() else float(value)
    if isinstance(value, dict):
        return {key: _normalize_dynamodb_value(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_normalize_dynamodb_value(item) for item in value]
    return value


def deserialize(dynamo_item):
    from decimal import Decimal

    def parse_value(v):
        type_key = list(v.keys())[0]
        val = list(v.values())[0]
        if type_key == "S":
            return val
        elif type_key == "N":
            return _normalize_dynamodb_value(Decimal(val))
        elif type_key == "BOOL":
            return val
        elif type_key == "NULL":
            return None
        elif type_key == "L":
            return [parse_value(i) for i in val]
        elif type_key == "M":
            return {k: parse_value(v2) for k, v2 in val.items()}
        else:
            return val
    return {k: parse_value(v) for k, v in dynamo_item.items()}


def _received_timestamp_us(value):
    """Parse a timezone-aware ISO receipt time without losing microseconds."""
    from datetime import datetime, timedelta, timezone

    received = datetime.fromisoformat(value)
    if received.tzinfo is None or received.utcoffset() is None:
        raise ValueError('timestamp_received must include a timezone')
    return (received - datetime(1970, 1, 1, tzinfo=timezone.utc)) // timedelta(microseconds=1)


def _use_received_timestamps(rows, anchor):
    """Estimate UTC acquisition times while retaining the collector intervals.

    The last sample of the latest timestamped batch is anchored to its receipt
    time. A single offset per capture keeps network jitter out of the features
    and window membership. Transport delay remains part of this estimate.
    """
    from datetime import datetime, timedelta, timezone

    stamp, received = anchor
    offset = _received_timestamp_us(received) - stamp
    epoch = datetime(1970, 1, 1, tzinfo=timezone.utc)

    def iso(value):
        return (epoch + timedelta(microseconds=value)).isoformat(timespec='microseconds')

    for row in rows:
        row['timestamp_received'] = received
        row['window_start_timestamp_us'] += offset
        row['window_end_timestamp_us'] += offset
        row['sample_timestamps_us'] = [stamp + offset for stamp in row['sample_timestamps_us']]
        row['window_start_timestamp'] = iso(row['window_start_timestamp_us'])
        row['window_end_timestamp'] = iso(row['window_end_timestamp_us'])
        row['sample_timestamps'] = [iso(stamp) for stamp in row['sample_timestamps_us']]


def rodar_modelo(itens, *, diagnostics=None):
    """Normalize radio metadata; report incompatible captures without classifying.

    Missing PHY mode is unknown: equal CSI lengths do not prove equal formats.
    Receipt time supplies an optional UTC estimate, not sampling intervals.
    """
    def integer(value):
        number = int(value)
        if number != value:
            raise ValueError(f'Expected an integer, got {value!r}')
        return number

    if diagnostics is None:
        diagnostics = []
    captures, anchors = {}, {}
    for item in itens:
        samples = item.get('samples', [item])
        received = item.get('timestamp_received')
        if received is not None:
            _received_timestamp_us(received)
        last_stamp = max((integer(sample['timestamp_us']) for sample in samples), default=None)
        for sample in samples:
            values = [integer(value) for value in sample['csi_raw']]
            if 'bandwidth_mhz' in sample:
                width = integer(sample['bandwidth_mhz'])
                if width not in (20, 40):
                    raise ValueError(f'Unsupported bandwidth_mhz: {width}')
                bandwidth = {20: 0, 40: 1}[width]
            else:
                bandwidth = sample.get('bandwidth')
                if bandwidth is not None:
                    bandwidth = integer(bandwidth)
                    if bandwidth not in (0, 1):
                        raise ValueError(f'Unsupported ESP bandwidth code: {bandwidth}')
            mode = sample.get('sig_mode', sample.get('rx_format'))
            packet = {
                'data': values,
                'len': len(values),
                'timestamp_us': integer(sample['timestamp_us']),
                'first_word': integer(sample.get('first_word_invalid', False)),
                'mac': str(sample['ap_mac']).strip().lower() if sample.get('ap_mac') is not None else None,
                'channel': sample.get('channel'),
                'bandwidth': bandwidth,
                'sig_mode': integer(mode) if mode is not None else None,
            }
            if packet['channel'] is not None:
                packet['channel'] = integer(packet['channel'])
            key = (item.get('device_id'), item.get('session_id'),
                   packet['mac'], packet['channel'], packet['bandwidth'], len(values), packet['sig_mode'])
            captures.setdefault(key, []).append(packet)
            if received is not None and (key not in anchors or last_stamp > anchors[key][0]):
                anchors[key] = (last_stamp, received)

    resultados = []
    for key, packets in captures.items():
        expected = {name: value for name, value in
                    (PROVENANCE['metadata'].get('input_filter') or {}).items()
                    if name not in ('mac', 'channel')}
        mismatches = {name: {'expected': value, 'actual': packets[0].get(name)}
                      for name, value in expected.items()
                      if str(packets[0].get(name, '')).strip() != str(value)}
        if mismatches:
            diagnostics.append(dict(device_id=key[0], session_id=key[1],
                                    status='unsupported_radio_format', presence_label=None,
                                    packet_count=len(packets), mismatches=mismatches))
            continue
        # A single packet cannot provide temporal features.
        if len(packets) < 2:
            diagnostics.append(dict(device_id=key[0], session_id=key[1],
                                    status='insufficient_data', presence_label=None,
                                    packet_count=len(packets)))
            continue
        rows = predict_input(packets, kind='raw')
        if not rows:
            diagnostics.append(dict(device_id=key[0], session_id=key[1],
                                    status='too_short', presence_label=None,
                                    packet_count=len(packets)))
        if key in anchors:
            _use_received_timestamps(rows, anchors[key])
        for row in rows:
            row.update(device_id=key[0], session_id=key[1])
        resultados.extend(rows)
    return resultados


def _json_safe(value):
    """Make model output serializable by json.dumps (including NaN values)."""
    import math
    import numpy as np

    if isinstance(value, dict):
        return {key: _json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_safe(item) for item in value]
    if isinstance(value, np.generic):
        value = value.item()
    if isinstance(value, float) and not math.isfinite(value):
        return None
    return value
    
def get_bucket(timestamp):

    """
    Determine length of bucket to insert items to aggregation table.
    """
    dt = datetime.fromisoformat(timestamp)
    dt = dt.astimezone(timezone.utc)

    bucket_minute = (dt.minute // 10) * 10

    bucket = dt.replace(
        minute=bucket_minute,
        second=0,
        microsecond=0
    )

    return bucket.isoformat()

def save_model_result(resultados):
    """Keep the table contract: id (String), result (Number), timestamp (ISO String).

    Use the estimated window acquisition time when the batch has a UTC receipt
    anchor. Otherwise timestamp records processing time, never device uptime.
    Only accepted binary presence predictions are persisted.
    """
    import uuid
    import boto3

    processing_time = datetime.now(timezone.utc)
    pending = []
    for item in resultados:
        if item.get('status') != 'ok' or item.get('state') not in (0, 1):
            continue
        timestamp = item.get('window_start_timestamp')
        if timestamp is None:
            timestamp = processing_time
            print('Sem timestamp_received: usando horário UTC de processamento para model_result.')
        else:
            if not isinstance(timestamp, str):
                raise ValueError('Window timestamp must be a timezone-aware ISO string')
            timestamp = datetime.fromisoformat(timestamp.replace('Z', '+00:00'))
            if timestamp.tzinfo is None or timestamp.utcoffset() is None:
                raise ValueError('Window timestamp must include a timezone')
        pending.append({
            'id': str(uuid.uuid4()),
            'result': int(item['state']),
            'timestamp': timestamp.astimezone(timezone.utc).isoformat(timespec='microseconds')
        })

    if not pending:
        print('Nenhum resultado válido para inserir em model_result.')
        return

    dynamodb = boto3.resource('dynamodb')
    result_table = dynamodb.Table('model_result')
    aggregate_table = dynamodb.Table('model_result_10m')

    print(f'Inserindo {len(pending)} resultados à tabela model_result')

    for item in pending:
        result_table.put_item(Item=item)

        result = int(item['result'])
        timestamp = item['timestamp']

        try:
            result_table.update_item(
                Key={'id': 'LATEST'},
                UpdateExpression='SET #r = :r, #ts = :ts',
                ConditionExpression='attribute_not_exists(#ts) OR #ts < :ts',
                ExpressionAttributeNames={
                    '#r': 'result',
                    '#ts': 'timestamp'
                },
                ExpressionAttributeValues={
                    ':r': result,
                    ':ts': timestamp
                }
            )
        except result_table.meta.client.exceptions.ConditionalCheckFailedException:
            pass

        bucket_start = get_bucket(timestamp)

        aggregate_table.update_item(
            Key={
                'series_id': 'occupancy',
                'bucket_start': bucket_start
            },
            UpdateExpression='ADD #total :one, #occupied :occupied',
            ExpressionAttributeNames={
                '#total': 'total',
                '#occupied': 'occupied_count'
            },
            ExpressionAttributeValues={
                ':one': 1,
                ':occupied': result
            }
        )

    print(f'{len(pending)} resultados inseridos, atualizados e agregados com sucesso')

def lambda_handler(event, context):
    """
    AWS Lambda entry point for a DynamoDB Stream event.

    Processes INSERT records. Exceptions are intentionally not swallowed:
    Lambda can retry the failed batch according to the event source mapping.
    """
    records = event.get('Records', [])
    print(f"Recebidos {len(records)} registros do DynamoDB Stream")

    itens = []
    for record in records:
        if record.get('eventName') != 'INSERT':
            continue

        dynamodb = record.get('dynamodb', {})
        new_image = dynamodb.get('NewImage')
        if not new_image:
            print("Registro INSERT sem NewImage; ignorando.")
            continue

        item = deserialize(new_image)
        itens.append(item)

    if not itens:
        print("Nenhum registro INSERT válido para processar.")
        return {
            'statusCode': 200,
            'body': json.dumps({
                'message': 'Nenhum registro INSERT para processar.',
                'received_records': len(records),
                'processed_records': 0,
                'results': []
            })
        }

    print(f"Processando {len(itens)} itens recebidos do DynamoDB.")

    issues = []
    resultados = rodar_modelo(itens, diagnostics=issues)
    if issues:
        print(json.dumps({'capture_issues': _json_safe(issues)}, allow_nan=False))

    aceitos = sum(1 for row in resultados if row.get('status') == 'ok')
    rejeitados = len(resultados) - aceitos

    resumo = {
        'received_records': len(records),
        'processed_records': len(itens),
        'windows': len(resultados),
        'accepted_windows': aceitos,
        'rejected_windows': rejeitados,
        'capture_issues': issues,
        'skipped_captures': len(issues)
    }

    # Presence labels, when available, come from the trained component mapping.
    print("Resumo da inferência:", json.dumps(resumo))
    print("Resultados:", json.dumps(_json_safe(resultados), allow_nan=False))

    save_model_result(resultados)

    return {
        'statusCode': 200,
        'body': json.dumps(_json_safe({**resumo, 'results': resultados}), allow_nan=False)
    } 